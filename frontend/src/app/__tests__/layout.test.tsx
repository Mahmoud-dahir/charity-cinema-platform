import { render } from '@testing-library/react';
import RootLayout, { metadata } from '../layout';
import React from 'react';

describe('RootLayout', () => {
  it('renders children inside the layout', () => {
    const originalError = console.error;
    console.error = jest.fn();

    const { getByText } = render(
      <RootLayout>
        <div data-testid="test-child">Layout Child Content</div>
      </RootLayout>
    );

    expect(getByText('Layout Child Content')).toBeInTheDocument();

    console.error = originalError;
  });

  it('exports the correct metadata', () => {
    expect(metadata).toBeDefined();
    expect(metadata.title).toEqual('Create Next App');
    expect(metadata.description).toEqual('Generated by create next app');
  });
});
